package dev.fogmap.fog;

import java.time.Duration;
import java.time.Instant;

/**
 * Ограничение скорости прироста площади — защита от накрутки лидерборда.
 *
 * <p>Клиент шлёт маску, а не трек, и проверить её «физику» напрямую нельзя: маска это просто
 * битовая карта. Зато можно проверить темп: за время между синхронизациями человек физически не
 * мог открыть больше, чем даёт ходьба по коридору шириной в два радиуса обзора на предельной
 * скорости.
 *
 * <p>Треки для проверки сюда сознательно не поднимаются. Таблица точек с временными метками — это
 * ещё более подробная история перемещений, чем маска, и хранить её ради античита значит лечить
 * одну утечку созданием худшей.
 *
 * <p>Что это ловит: заливку континента одним запросом, то есть мгновенный выход в топ. Чего не
 * ловит: медленную равномерную накрутку ботом. Она остаётся возможной, но перестаёт быть
 * бесплатной — требует держать процесс месяцами.
 */
final class GrowthBudget {

    /**
     * Скорость перемещения, 72 км/ч.
     *
     * <p>Намеренно не 200 км/ч: тот порог на клиенте отбраковывает телепорты, то есть отвечает на
     * вопрос «бывает ли такой скачок вообще». Здесь вопрос другой — с какой скоростью человек
     * перемещается длительно. 72 км/ч покрывает велосипед, город на машине и электричку.
     */
    private static final double SPEED_MPS = 20.0;

    /** Ширина вскрываемого коридора: два радиуса обзора. */
    private static final double CORRIDOR_WIDTH_M = 2 * 100.0;

    /** Запас на округления площади и расхождение часов клиента с сервером. */
    private static final double SLACK = 2.0;

    /**
     * Стартовая фора для первой синхронизации: около 4.8 км².
     *
     * <p>Здесь есть неустранимый компромисс. Человек мог неделю ходить офлайн и только потом
     * завести аккаунт — сервер о той неделе ничего не знает и такой первый синк урежет. Но
     * увеличивать фору нельзя: именно первый синк накрутчику и нужен, чтобы разом выйти в топ.
     */
    private static final Duration GRACE = Duration.ofMinutes(10);

    private GrowthBudget() {
    }

    /** Сколько квадратных метров можно принять за промежуток. */
    static long allowedFor(Instant since, Instant now) {
        long seconds = Math.max(0, Duration.between(since, now).plus(GRACE).toSeconds());
        return Math.round(seconds * SPEED_MPS * CORRIDOR_WIDTH_M * SLACK);
    }
}
